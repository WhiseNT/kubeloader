// 丑写法 03 · 全部挤成一行
// ============================================
// requires-transform
//
// 契约：整段代码挤在一行里也不能出错。
// 类、字段、展开、解构默认值、计算属性名、逻辑赋值、形参解构全塞在一行。

class A{m(){return 1}}const a=new A();const arr=[...[1,2],3];const {v=9}={};const key='k'+1;const obj={[key]:5};let n=null;n||=7;function f({p=4}){return p}

__check('一行流：类方法', a.m(), 1)
__check('一行流：数组展开', arr.join(','), '1,2,3')
__check('一行流：解构默认值', v, 9)
__check('一行流：计算属性名', obj.k1, 5)
__check('一行流：逻辑赋值', n, 7)
__check('一行流：形参解构默认值（缺省）', f({}), 4)
__check('一行流：形参解构默认值（给值）', f({ p: 1 }), 1)
