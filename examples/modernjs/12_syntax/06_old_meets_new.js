// ============================================
// requires-transform
//
// 契约：老语法（var、函数声明、if、try）与新语法混在一处时，每一处改写都要
// 落在正确的下标上，不能把隔壁的语句一起吞掉。

var 键 = 'k'

function 取对象(是否命中) {
    var 对象 = { [键]: '变量键', ['字面' + '串']: '拼接键' }
    try {
        if (是否命中) {
            throw new Error('命中')
        }
        return 对象
    } catch { // 可选 catch 绑定
        return 对象
    }
}

var 空值 = null
空值 ??= '补上'
var 或值 = 0
或值 ||= 7
var 与值 = 'x'
与值 &&= 与值 + 'y'

__check('计算属性名（变量键）', 取对象(true)[键], '变量键')
__check('计算属性名（拼接键）', 取对象(true)['字面串'], '拼接键')
__check('可选 catch 生效', 取对象(false)['字面串'], '拼接键')
__check('??= 展开', 空值, '补上')
__check('||= 展开', 或值, 7)
__check('&&= 展开', 与值, 'xy')
