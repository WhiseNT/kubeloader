class 计算器 {
    constructor(初始值) {
        this.累计 = 初始值
        this.记录 = []
    }

    static 建(初始值) {
        return new 计算器(初始值)
    }

    get 当前值() {
        return this.累计
    }

    set 当前值(新值) {
        this.累计 = 新值
    }

    加({ 数量 = 1, 备注 = '无' }) {
        this.累计 += 数量
        this.记录.push(备注)
        return this
    }
}

const 计算器实例 = 计算器.建(10)
计算器实例.加({ 数量: 5, 备注: '加五' }).加({})

const { 当前值: 读到的值 } = 计算器实例
let 可变 = null
可变 ??= 3

__check('中文类名与静态方法', 计算器实例 instanceof 计算器, 'true')
// 10（建） + 5（加五） + 1（第二次调用走默认值） = 16
__check('中文 getter', 读到的值, 16)
__check('中文 setter', (计算器实例.当前值 = 20, 计算器实例.当前值), 20)
__check('中文模式键 + 形参默认值', 计算器实例.记录.join(','), '加五,无')
__check('??= 与中文变量', 可变, 3)
