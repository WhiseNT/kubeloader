// ============================================
// 语法边角 08 · 展开语法夹在注释与空白里
// ============================================
// requires-transform
//
// 契约：展开可以出现在数组字面量、函数调用、成员调用（要保住 this）、
// 构造调用里；周围塞满注释与换行时，仍要落在正确的下标上，不能把
// 相邻的实参一起吞掉。

class 收集器 {
    constructor(前缀) {
        this.前缀 = 前缀
        this.项 = []
    }

    加(...值) { // 剩余形参
        for (var i = 0; i < 值.length; i++) {
            this.项.push(this.前缀 + 值[i])
        }
        return this
    }

    取() {
        return this.项
    }
}

var 前 = [1, 2]
var 后 = [4, 5]
var 合并 = [ /* 前 */ ...前 /* 中 */, 3 /* 中后 */, ...后 /* 后 */ ]
var 器 = new 收集器(/* 实参前 */ 'x' /* 实参后 */)
var 新器 = new 收集器(...[/* 构造展开 */ 'y']) // 构造调用里的展开（被构造者要能直接认出来）
器.加(/* 展开前 */ ...前 /* 展开后 */) // 成员调用展开要保住 this
器.加(...后) // 分开写：接收者是简单标识符才支持，链式（接收者是调用结果）见 07_reject/12

function 求和(a, b, c) {
    return a + b + c
}

var 和 = 求和(/* 调用前 */ ...[1, 2] /* 调用中 */, 3 /* 调用后 */)

__check('数组字面量里的展开', 合并.join(','), '1,2,3,4,5')
__check('成员调用展开 + this', 器.取().join(','), 'x1,x2,x4,x5')
__check('构造调用里的展开', 新器.前缀, 'y')
__check('调用里的展开 + 相邻实参', 和, 6)
