// ============================================
// 语法边角 11 · 注释 / 字符串 / 模板串 / 正则里写着像代码的东西
// ============================================
// requires-transform
//
// 契约：注释、字符串、模板串文本段、正则里的 `class`、`return {`、`}`、`{`
// 都不是代码。扫描器一旦把它们当代码，就会对着一个不存在的结构改写出错；
// 花括号计数被带跑的话，类的边界会整体错位。

// class 假类 { constructor() { this.x = 1 } }
/* return { a, b } */
const 文本 = 'class 假类 { } return { a: 1 }'
const 模板 = `class 假类 { } 还有 ${'return { a }'}`
const 正则 = /class\s+\S+/ // 注意：\w 不匹配中文，别用 \w+\s*\{

class 真类 { // 类头注释里也可以有 } 和 {
    constructor() {
        // 这一行注释里有 } 和 {，花括号计数不能被它带跑
        this.值 = 1 // 行尾也有 } {
    }

    get 单() {
        return this.值
    }
}

__check('字符串里的 class 不是类', 真类 !== undefined, 'true')
__check('注释里的花括号不影响计数', new 真类().单, 1)
__check('模板串里的 class 不是类', 模板.indexOf('假类') > 0, 'true')
__check('正则能匹配类写法文本', 正则.test(文本), 'true')
