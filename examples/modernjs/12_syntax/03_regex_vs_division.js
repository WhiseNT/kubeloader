// ============================================
// 语法边角 03 · 正则字面量与除号的歧义
// ============================================
// requires-transform
//
// 契约：正则字面量里的 `//`、`/*`、`{}` 都不是注释和代码块；反过来，
// 除号也不是正则。判错一头会把后面整段代码当注释吞掉（或反过来把它改坏），
// 所以每一处都要在「字符串 / 注释 / 正则 / 除法」之间分对。

const 文本 = 'https://example.com/a/b'
const 去协议 = 文本.replace(/https?:\/\//, '') // 正则里带 //，不能被当注释
const 花括号 = 'x{}y'.match(/[{}]/g) // 正则字符类里带花括号
const 斜杠 = 'a/b'.split(/\//) // 正则里带转义斜杠
const 除号链 = 10 / 2 / 5 // 除号链，别当正则
const 除号后注释 = 8 / 2 // 行尾注释紧跟在除号表达式后面

class 正则混合 {
    static 计数(值) {
        return 值 / 2 // 类方法体里的除号
    }

    static 判断(文本) {
        return /class\s+\w+/.test(文本) // 正则里带 class
    }
}

__check('正则里的协议头', 去协议, 'example.com/a/b')
__check('正则字符类里的花括号', 花括号.join(''), '{}')
__check('正则里转义斜杠', 斜杠.join('|'), 'a|b')
__check('除号链', 除号链, 1)
__check('除号后行尾注释', 除号后注释, 4)
__check('类里的除号', 正则混合.计数(9), 4.5)
__check('正则里带 class 不算类', 正则混合.判断('class Foo'), 'true')
