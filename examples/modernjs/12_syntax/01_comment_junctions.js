// ============================================
// 语法边角 01 · 生成代码紧挨着源码里的行尾注释
// ============================================
// requires-transform
//
// 契约：转换器会在很多位置往源码里「插生成代码」——右值之后、方法体尾部、
// 形参表、类头、访问器收尾……只要这些位置刚好停在一行注释里，插进去的东西
// 就会被整段吞掉，而且 Rhino 一声不响地算出错误答案。
// 本文件把每一个这样的位置都写一遍。

class 注释边角 { // 类头行尾注释
    constructor(值) { // 构造器签名行尾注释
        this.字段 = 值 // 字段赋值行尾注释
    } // 构造器收尾行尾注释

    get 双倍() { // getter 签名行尾注释
        return this.字段 * 2 // getter 体行尾注释
    } // getter 收尾行尾注释

    set 双倍(v) { // setter 签名行尾注释
        this.字段 = v // setter 体行尾注释
    } // setter 收尾行尾注释

    static 建(参数) { // 静态方法签名行尾注释
        const { 起点 = 1 } = 参数 || {} // 解构右值行尾注释
        return new 注释边角(起点) // new 调用行尾注释
    } // 静态方法收尾行尾注释
} // 类收尾行尾注释

const 实例 = new 注释边角(3) // new 行尾注释
let 累加 = 0
累加 ||= 实例.双倍 // 逻辑赋值右值行尾注释

__check('类头与构造器里的行尾注释', 实例.字段, 3)
__check('getter 前后的行尾注释', 实例.双倍, 6)
__check('静态方法 + 解构默认值', 注释边角.建({}).字段, 1)
__check('逻辑赋值', 累加, 6)
