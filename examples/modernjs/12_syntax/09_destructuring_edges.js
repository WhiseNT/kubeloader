// ============================================
// 语法边角 09 · 解构的边角（支持范围内的那些）
// ============================================
// requires-transform
//
// 契约：对象 / 数组模式里的默认值，在声明与函数形参里都要能正确摊平，
// 而且必须满足两条语义：右值只求值一次；默认值只在取到 undefined 时求值
// （0、''、false 都不该触发）。不支持的形式（嵌套模式、数组 rest、
// 一条声明两个模式、for-of）都写在 07_reject 里。

var 取值次数 = 0

function 造值() {
    取值次数 = 取值次数 + 1
    return { 有: 1, 数: 0 }
}

function 默认值() {
    取值次数 = 取值次数 + 1
    return '默认'
}

var { 有, 缺 = 默认值(), 数 = 99 } = 造值()

var { 甲: 别名 = '未给' } = { 甲: '给了' }
var { '带引号的键': 引号值 = '默认' } = {}
var [, 第二 = 2, 第三 = 3] = [1, undefined]

function 拿默认({ 名 = '匿名', 龄 = 0 }) {
    return 名 + '/' + 龄
}

class 解构类 {
    constructor(配置) {
        var { 尺寸 = 3 } = 配置 || {} // 类里的解构
        this.尺寸 = 尺寸
    }
}

__check('右值只求值一次 + 默认值只在该用时求值', 取值次数, 2)
__check('有值就用有值', 有, 1)
__check('undefined 才用默认值', 缺, '默认')
__check('0 不触发默认值', 数, 0)
__check('重命名 + 默认值', 别名, '给了')
__check('带引号的键 + 默认值', 引号值, '默认')
__check('数组空位 + 默认值', 第二 + '' + 第三, '23')
__check('函数形参里的模式（走默认）', 拿默认({}), '匿名/0')
__check('函数形参里的模式（给值）', 拿默认({ 名: '甲', 龄: 7 }), '甲/7')
__check('类里的解构', new 解构类({}).尺寸, 3)
