// ============================================
// 语法边角 05 · 自动分号插入（ASI）与跨行表达式
// ============================================
// requires-transform
//
// 契约：不写分号时语句边界由换行与 ASI 决定。转换器按行切分语句，
// 一旦把「上一条的尾巴」和「下一条的开头」粘在一起，或者把续行当成新语句，
// 就会静默算错。这里把几种典型续行都写一遍。

class 链式 {
    constructor(基础) {
        this.基础 = 基础
    }

    加(值) {
        this.基础 = this.基础 + 值
        return this
    }

    取值() {
        return this.基础
    }
}

const 结果 = new 链式(1) // 不写分号
    .加(2) // 下一行以 . 开头 → 续行
    .加(3)
    .取值()

const 三元 = true
    ? '是'
    : '否'

const 跨行数组 = [
    1,
    2,
]
const 跨行对象 = {
    甲: 1,
    乙: 2,
}

__check('跨行链式调用', 结果, 6)
__check('跨行三元', 三元, '是')
__check('跨行数组', 跨行数组.join(','), '1,2')
__check('跨行对象', 跨行对象.甲 + 跨行对象.乙, 3)
