// ============================================
// 语法边角 02 · 行内块注释夹在「生成代码要插进去」的位置
// ============================================
// requires-transform
//
// 契约：与 01 是同一个位置集合，但换成行内块注释。块注释不会吞掉后面的代码，
// 所以这一组盯的是另一件事：表头 / 形参表的识别。那里只跳空白、不跳注释的话，
// 构造函数会被判定成「不是构造函数」，成员会被整个漏掉。

class 块注释边角 /* 类名后 */ {
    /* 构造器前 */ constructor(值 /* 形参后 */) /* 花括号前 */ {
        this.字段 /* 字段名后 */ = 值 /* 值后 */
    } /* 构造器尾 */

    /* getter 前 */ get 双倍(/* 空形参 */) /* 花括号前 */ {
        return this.字段 * 2 /* 乘以二 */
    } /* getter 尾 */

    /* setter 前 */ set 双倍(v /* 形参后 */) /* 花括号前 */ {
        this.字段 = v /* 赋值 */
    } /* setter 尾 */
}

const 实例 /* 常量名后 */ = new 块注释边角(/* 实参前 */ 4 /* 实参后 */) /* new 尾 */
const 取反 = -实例.双倍 /* 一元表达式 */

__check('类头与成员里的块注释', 实例.双倍, 8)
__check('块注释里的 setter', (实例.双倍 = 5, 实例.字段), 5)
__check('块注释里的 new 与实参', 取反, -8)
