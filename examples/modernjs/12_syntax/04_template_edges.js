// ============================================
// 语法边角 04 · 模板串的边界
// ============================================
// requires-transform
//
// 契约：模板串的文本段里可以出现 `{` `}` `//` `/*`，都不该被当成代码或注释；
// 而 `${}` 里是真代码，里面的现代写法要照常处理。模板串后面紧跟行尾注释
// 也要能正确收尾（收尾的括号别被注释吞掉）。

const 名 = '世界'
const 文本段带花括号 = `前面 { 后面 } 结束`
const 段里带注释符号 = `// 不是注释 /* 也不是 */`
const 段里带类写法 = `class 假类 { m() {} }`
const 插值 = `你好，${名}！`
const 插值里带花括号 = `集合：${'{' + '}'}`

class 模板类 {
    constructor(前缀) {
        this.前缀 = 前缀
    }

    get 消息() {
        return `${this.前缀}${1 + 1}` // 模板串后面跟行尾注释
    }
}

__check('文本段里的花括号', 文本段带花括号, '前面 { 后面 } 结束')
__check('文本段里的注释符号', 段里带注释符号, '// 不是注释 /* 也不是 */')
__check('文本段里的类写法', 段里带类写法, 'class 假类 { m() {} }')
__check('插值', 插值, '你好，世界！')
__check('插值里带花括号', 插值里带花括号, '集合：{}')
__check('类里的模板串 + 行尾注释', new 模板类('x').消息, 'x2')
