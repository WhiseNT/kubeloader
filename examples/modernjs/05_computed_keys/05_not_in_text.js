// ============================================
// 05 · 文本里的计算属性名不该被改写
// ============================================
// requires-transform
//
// 字符串/模板串/注释里出现 {[k]: 1} 这种片段太正常了（写文档、打日志）。
// 只有真代码才改写。

const s1 = '{[k]: 1}'
const s2 = `说明：{[k]: 2}`
// 注释里的 {[k]: 3}
/* 块注释里的 {[k]: 4} */

const k = 'a'
const real = { [k]: 5, plain: 6 }

__check('字符串里的计算属性名保持原样', s1, '{[k]: 1}')
__check('模板串文本保持原样', s2, '说明：{[k]: 2}')
__check('同文件里真的计算属性名仍生效', real.a, 5)
__check('同一对象里的普通成员仍生效', real.plain, 6)
