// ============================================
// 12 · 链式调用的接收者是「调用结果」时的展开：目前不支持
// ============================================
// expect-error: syntax error
//
// 写成 a.m(...x).n(...y) 时，第二个调用的接收者是 `a.m(...x)` 这个调用结果。
// 要保住 this 就得让接收者只求值一次，那需要包一层 IIFE；与 08 同一类问题，
// 现在的实现选择**不改写**。
//
// 为什么宁可报错：改成 `接收者.n.apply(null, args)` 的话，非严格模式下
// apply(null) 的 this 变成全局对象，方法体里读 this.x 会静默拿到 undefined。
// 宁可留一条明确的语法错误，也不要静默算错值。
//
// 替代写法：把第一个调用的结果存进变量，再展开调用。
//   const 器 = new 收集器('x');  器.加(...前);  器.加(...后)

class 收集器 {
    constructor(前缀) {
        this.前缀 = 前缀
        this.项 = []
    }

    加(...值) {
        for (var i = 0; i < 值.length; i++) {
            this.项.push(this.前缀 + 值[i])
        }
        return this
    }

    取() {
        return this.项
    }
}

const 器 = new 收集器('x')
const 前 = [1, 2]

__check('分开写是没问题的（对照）', (器.加(...前), 器.取().join(',')), 'x1,x2')

__check('这一行不该被执行到', 器.加(...前).加(...[3]).取().join(','), 'never')
