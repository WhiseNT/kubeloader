// 10 · 模板串 ${} 里写现代语法：目前不够用
// ============================================
// expect-error: syntax error
//
// 词法掩码把模板串整段当成「文本」处理，因此 ${} 里的**代码**也没被转换 ——
// 在 ${} 里写展开 `...`、数字分隔符、嵌套模板串等，原样留给 Rhino 就会报语法错误
// （响亮失败，不会静默算错值）。
//
// 替代写法：把 ${} 里的表达式先算好，再用模板串；或改成字符串拼接。

const 数据 = [1, 2, 3]

// 下面这行里 ${} 用了展开 → 不会被转换
const 坏 = `长度${[...数据].length}`

__check('这一行不该被执行到', 坏, 'never')
