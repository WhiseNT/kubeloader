// ============================================
// 09 · 点两侧带空格的成员调用展开：目前不支持
// ============================================
// expect-error: syntax error
//
// 写成 `o . m(...args)`（点前后都有空格）时，回扫被调用者只拿到 ".m" ——
// 接收者被空白截断了。要保住 this 就得把接收者补回来并保证只求值一次，
// 现在的实现选择**不改写**。
//
// 为什么宁可报错：原先这类情况会退化成 `o.m.apply(null, args)`，而非严格模式下
// apply(null) 的 this 是全局对象 —— 方法体里读 this.x 静默拿到 undefined
// （实测直接算出 NaN），属于最危险的静默算错。
//
// 替代写法：把点两侧的空格去掉即可（`o.m(...args)`），这一行下面有对照。

const obj = {
    base: 1,
    add(a, b) {
        return this.base + a + b
    }
}

// 去掉空格就没问题（对照）
__check('不带空格的写法是支持的', obj.add(...[1, 2]), 4)

__check('这一行不该被执行到', obj . add(...[1, 2]), 'never')
