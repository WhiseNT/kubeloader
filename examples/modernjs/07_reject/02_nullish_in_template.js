// ============================================
// 02 · 模板串 ${} 里的 ?? 也要被拦下
// ============================================
// expect-error: ??
//
// 检查器只在「代码」里找 ??，字符串和注释里的不算。
// 模板串里的 ${...} 是代码，必须照样拦——否则会漏过去算错值。

const value = null
const text = `结果是 ${value ?? 'default'}`

__check('这行不该被执行到', text, 'never')
