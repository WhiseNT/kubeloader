// ============================================
// 11 · 一条声明里出现两个解构模式：目前不支持
// ============================================
// expect-error: before function parameters
//
// `var {a = 1} = x, {b = 2} = y` 这种写法，第一个模式能摊平，
// 但第二个模式前面没有 var/let/const 关键字（只有逗号），
// 转换器认不出它也是声明里的模式，于是原样留着 → Rhino 报语法错误。
//
// 好在这是**响亮失败**，不会静默算错值。
// 替代写法：分成两条声明。

var { a = 1 } = {}
var { b = 2 } = {}

__check('拆成两条声明就没问题（对照）', a + b, 3)

var { c = 1 } = {}, { d = 2 } = {}

__check('这一行不该被执行到', c + d, 'never')
