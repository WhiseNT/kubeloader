// ============================================
// 怪写法 04 · 模板串：文本段与 ${} 代码段的边界
// ============================================
// requires-transform
//
// 契约：模板串的文本段不算代码（里面的 class / {...} / ... 都只是字符），
// 而 ${} 里是货真价实的代码。
//
// 注意：这一份只放「${} 里是 Rhino 原生写法」的情况。
// 若在 ${} 里写现代语法（展开、数字分隔符、嵌套模板串等），当前不会被转换 ——
// 见 07_reject/10。

const 内层 = `内${1 + 1}层`
const 花括号文本 = `文本 } { 加代码 ${'}'} 与 ${'{'}`
const 像类 = `class A { m() { return '}' } }`
const 像展开 = `f(...args) 与 ${[1, 2].length}`
const 对象取值 = `a${ { b: 7 }.b }c`
const 条件 = `结果${1 < 2 ? '小' : '大'}`
const 空串 = `${''}`
const 反斜杠 = `反斜杠 \\ 与 } `
const 方法调用 = `长度${'ab'.length}`

class WithTemplate {
    m() {
        return `方法里的 } 与 ${this.constructor === WithTemplate ? 'yes' : 'no'}`
    }
}

const 拼接 = `${内层}-${花括号文本}`

__check('模板串插值', 内层, '内2层')
__check('文本里的花括号与插值', 花括号文本, '文本 } { 加代码 } 与 {')
__check('模板串里的整段代码文本', 像类, "class A { m() { return '}' } }")
__check('文本里的 ... 只是字符', 像展开, 'f(...args) 与 2')
__check('插值里是对象取值', 对象取值, 'a7c')
__check('插值里是三目', 条件, '结果小')
__check('插值空串', 空串, '')
__check('模板串里的反斜杠', 反斜杠, '反斜杠 \\ 与 } ')
__check('插值里调方法', 方法调用, '长度2')
__check('方法里的模板串', new WithTemplate().m().indexOf('yes') > 0, 'true')
__check('多个模板串拼接', 拼接, '内2层-文本 } { 加代码 } 与 {')
