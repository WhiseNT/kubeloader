// ============================================
// 怪写法 02 · 字符串转义里藏着结构字符
// ============================================
// requires-transform
//
// 契约：字符串里「看起来像结构」的内容一律不许被当成结构。
// 这里用转义写出 } { ' " 反斜杠，还有以反斜杠收尾的字符串 ——
// 词法扫描稍有偏差就会被骗到。

const a = '\u007d'   // 内容是 }
const b = '\x7d'     // 同上，十六进制写法
const c = '\\'       // 内容是一个反斜杠
const d = 'a\\'      // 以转义反斜杠收尾
const e = '}' + '\\' // 先来一个真 }
const f = '\u0027'   // 内容是单引号
const g = "a\"b"     // 转义的双引号
const h = '\\\\}'    // 两个反斜杠 + 一个 }
const i = '\u005c'   // 内容是反斜杠

// 注释里也有 \ 与 } 与 ' 与 " 与反斜杠收尾 \
/* 块注释里：{ } ' " \ 与 class A { } */

const 图案 = /[\}\]\\]/

class WithStrings {
    m() {
        return '}' + "\\" + '\u007d'
    }
}

__check('\\u007d 是 }', a, '}')
__check('\\x7d 是 }', b, '}')
__check('反斜杠字符串', c, '\\')
__check('以反斜杠收尾', d, 'a\\')
__check('真 } 与反斜杠拼接', e, '}\\')
__check('转义单引号', f, "'")
__check('转义双引号', g, 'a"b')
__check('双反斜杠加 }', h, '\\\\}')
__check('转义反斜杠字符', i, '\\')
__check('正则里的 } 与反斜杠', String(图案.test('}')), 'true')
__check('类方法里拼接这些字符', new WithStrings().m(), '}\\}')
__check('字符串里的 } 不影响类体边界', new WithStrings().m().length, 3)
