// ============================================
// 怪写法 06 · 默认值是复杂表达式，且只在需要时求值
// ============================================
// requires-transform
//
// 契约：默认值可以任意表达式；而且**只在缺省时才求值**（有副作用时算错就是静默 bug）。

let 调用次数 = 0

function 取默认() {
    调用次数 += 1
    return 'p'
}

const 助手 = {
    m() {
        return 'm'
    }
}

const { a = 取默认(), b = 助手.m(), c = { x: 1 }.x, d = [1, 2].length, e = '}' } = {}
var [ f = 取默认().length ] = []

__check('默认值是函数调用', a, 'p')
__check('默认值是方法调用', b, 'm')
__check('默认值是对象取值', c, 1)
__check('默认值是数组长度', d, 2)
__check('默认值是含 } 的字符串', e, '}')
__check('数组模式里的默认值也是表达式', f, 1)
__check('缺省两次 → 求值两次', 调用次数, 2)

const 有值 = { g: 'have' }
const { g = 取默认() } = 有值

__check('有值时用真值', g, 'have')
__check('有值时默认值不该被求值', 调用次数, 2)

const { hh = 取默认() } = { hh: undefined }
__check('值是 undefined → 用默认值', hh, 'p')
__check('undefined 才求值', 调用次数, 3)
