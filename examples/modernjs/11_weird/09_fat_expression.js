// ============================================
// 怪写法 09 · 又长又深的单个表达式
// ============================================
// requires-transform
//
// 契约：一整个表达式里嵌套多层展开 / 计算属性名 / 箭头函数，也要逐层改对。
// 下面这行故意写得极长，专治「一次只改最内层、靠多轮收敛」那套逻辑。

const 数据 = { 组: [{ 名: 'a', 值: [1, 2] }, { 名: 'b', 值: [3] }] }

const 结果 = [...数据.组].map(g => ({ 名: g.名, 合计: [...g.值].reduce((s, v) => s + v, 0) })).filter(g => g.合计 > 0).map(g => g.名 + '=' + g.合计).join('|')

__check('超长表达式链', 结果, 'a=3|b=3')

const 深 = ({ [['k'].join('')]: [...[1, 2]].length }).k
__check('计算属性名 + 展开混在一个表达式里', 深, 2)

const 再深 = ({ ...{ 内: { ...{ 值: [...[9]].length } } } }).内.值
__check('对象展开套两层', 再深, 1)

const 调用链 = [1, 2, 3].map(function (x) { return [x, x].length }).reduce(function (a, b) { return a + b }, 0)
__check('长调用链', 调用链, 6)

const 混合 = [...[1, 2], ...[3]].map(x => ({ [x > 1 ? 'big' : 'small']: x }))
__check('展开 + 计算键 + 三目当键名（第一个）', 混合[0].small, 1)
__check('展开 + 计算键 + 三目当键名（第三个）', 混合[2].big, 3)
