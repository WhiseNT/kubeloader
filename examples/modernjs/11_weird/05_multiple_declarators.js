// ============================================
// 怪写法 05 · 一个声明里多个模式 + 多个声明符
// ============================================
// requires-transform
//
// 契约：同一条声明语句里混着模式与普通声明符时，每个都要正确摊平，
// 而且不能多出 / 少掉声明符。

var { a = 1 } = {}, c = 3
const { d = 4 } = {}, f = 6
let [ i = 9 ] = [], k = 11

__check('var：模式默认值', a, 1)
__check('var：普通声明符跟在后面', c, 3)
__check('const：模式默认值', d, 4)
__check('const：普通声明符', f, 6)
__check('let：数组模式默认值', i, 9)
__check('let：普通声明符', k, 11)

var { 有值 = 100 } = { 有值: 5 }, 合计 = 有值 + 1
__check('模式摊平后普通声明符能引用它', 合计, 6)
