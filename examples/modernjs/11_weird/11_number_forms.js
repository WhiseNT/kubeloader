// ============================================
// 怪写法 11 · 各种数字写法
// ============================================
// requires-transform
//
// 契约：数字字面量的各种合法写法都要能过，且分隔符只在下划线的位置去掉。
// 特别是「小数里的分隔符」（1.000_5）—— 回扫遇到小数点不能就把 token 判没了。

const 科学 = 1e3
const 科学负 = 1e-3
const 省略整数部分 = .5
const 省略小数部分 = 5.
const 分组整数 = 1_000
const 分组小数 = 1_000.5
const 分组小数位 = 1.000_5
const 大数 = 12_345_678
const 负数 = -1_000
const 十六 = 0xFF_FF
const 二 = 0b1010_1010
const 八 = 0o17_17
const 表达式 = 1_000 + 2_000

class 数值 {
    static 上限 = 9_999
    m() {
        return 1_234
    }
}

__check('科学计数法', 科学, 1000)
__check('负指数', 科学负, 0.001)
__check('省略整数部分', 省略整数部分, 0.5)
__check('省略小数部分', 省略小数部分, 5)
__check('整数分组', 分组整数, 1000)
__check('小数分组', 分组小数, 1000.5)
__check('小数位里的分组', 分组小数位, 1.0005)
__check('多段分组', 大数, 12345678)
__check('负数分组', 负数, -1000)
__check('十六进制分组', 十六, 65535)
__check('二进制分组', 二, 170)
__check('八进制分组', 八, 975)
__check('参与运算', 表达式, 3000)
__check('静态字段里的分组', 数值.上限, 9999)
__check('方法里的分组', new 数值().m(), 1234)

const 标识符带下划线 = 1
const _前后都能用 = 2
__check('下划线开头/结尾的标识符不被误删', 标识符带下划线 + _前后都能用, 3)
