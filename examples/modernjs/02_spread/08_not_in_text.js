// ============================================
// 08 · 文本里的 ... 不能被当成代码改写
// ============================================
// requires-transform
//
// 字符串、模板串、注释里出现 ... 的地方多得是（比如日志模板、正则说明）。
// 一旦按纯文本替换，就会把文案改坏。

const src = 'f(...args)'
const tpl = `call(...args)`
const re = /\.\.\./

// 这行注释里的 ...a 也不该被改写
/* 块注释里的 ...b 同理 */

const real = [1, ...[2, 3]]

__check('字符串里的 ... 保持原样', src, 'f(...args)')
__check('模板串文本里的 ... 保持原样', tpl, 'call(...args)')
__check('正则里的 ... 保持原样', String(re.test('...')), 'true')
__check('同一份文件里真展开仍生效', real.join(','), '1,2,3')
