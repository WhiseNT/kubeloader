// ============================================
// 02 · 函数调用里的展开
// ============================================
// requires-transform
//
// 展开可以出现在实参列表的任何位置：最前面、中间、最后面，甚至可以出现多次。

function sum3(x, y, z) {
    return x + y + z
}

const nums = [1, 2, 3]

__check('整体展开', sum3(...nums), 6)
__check('展开 + 前置实参', sum3(0, ...[1, 2]), 3)
__check('展开 + 后置实参', sum3(...[1, 2], 3), 6)
__check('多次展开', sum3(...[1], ...[2, 3]), 6)
__check('展开变量', sum3(...nums), 6)

const more = [1, 2, 3, 4]
__check('多出的实参按 JS 语义忽略', sum3(...more), 6)

const less = [1, 2]
__check('实参不足时是 NaN', String(sum3(...less)), 'NaN')
